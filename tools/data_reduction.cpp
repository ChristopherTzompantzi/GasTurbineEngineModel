// =============================================================================
// data_reduction.cpp
// -----------------------------------------------------------------------------
// Phase 6 — Data Reduction Model
//
// PURPOSE:
//   Computes Kurzke-Riegler map scale factors by running the turbofan cycle
//   at multiple power settings and comparing cycle output against "measured"
//   data. With real engine data, replace the synthetic operating points with
//   actual test cell or flight test measurements.
//
// WHAT IT DOES:
//   1. Runs the turbofan cycle at N operating points (power settings)
//   2. Records station data as synthetic "measurements" at each point
//   3. Computes four scale factors per component at each operating point:
//        s_Wc = Wc_perf / Wc_map
//        s_Nc = Nc_perf / Nc_map
//        s_PR = (PR_perf - 1) / (PR_map - 1)
//        s_Ef = eff_perf / eff_map
//   4. Averages scale factors across all operating points (MDP Multi-
//      Design-Point method)
//   5. Writes updated SCALE_* fields to the map files
//   6. Prints a data reduction report
//
// NPSS ALIGNMENT:
//   Mirrors NPSS "flight test data correlation" mode.
//   Multi-Design-Point (MDP) method — same as Boeing BRE NPSS workflow.
//   Reference: "The Development of an NPSS Engine Cycle Model to Match
//   Engine Cycle Data, Using a Multi-Design-Point Method", AIAA 2021-0876.
//
// SYNTHETIC DATA NOTE:
//   Operating points are generated by running our own cycle model at
//   different shaft speeds. This validates the infrastructure.
//   Replace with real test cell data (CSV or similar) when available.
//   Format for real data substitution documented in measured_data section.
//
// SCALE FACTOR FORMULAS (Kurzke & Riegler, ASME 2000-GT-0006):
//   s_Wc = Wc_perf / Wc_map_at_operating_point
//   s_Nc = Nc_perf / Nc_map_at_operating_point
//   s_PR = (PR_perf - 1) / (PR_map_at_operating_point - 1)
//   s_Ef = eff_perf / eff_map_at_operating_point
//
// MAP FILE UPDATE:
//   Writes SCALE_PR, SCALE_EFF, SCALE_WC, SCALE_NC to map file headers.
//   Preserves all other map content unchanged.
//
// USAGE:
//   Run from build directory:
//     ./data_reduction
//   Map files in ../maps/synthetic/ are updated in place.
//   Run GasTurbineEngineModel after to verify updated maps.
//
// UNITS — SI throughout:
//   Wc   [kg/s corrected]
//   Nc   [RPM corrected]
//   PR   [-]
//   eff  [-]
// =============================================================================

